# Addition 
puts 1 + 1 #=> 2

# Substraction 
puts 2 - 1 #=> 1

# Multiplication
puts 2 * 2 #=> 4

# Division
puts 10 / 5 #=> 2

# Exponent
puts 2 ** 2 #=> 4
puts 3 ** 4 #=> 81

# Modulus (find the remainder of division)
puts 8 % 2 #=> 0 (8/2 = 4; no remainder)
puts 10 % 4 #=> 2 (10/4 = 2 with a remainder of 2)

# Integers
puts 17 / 5 #=> 3, not 3.4

# Float 
puts 17 / 5.0 #=> 3.4

# To convert an integer to float:
puts 13.to_f #=> 13.0

#To conver a float to integer:
puts 13.0.to_i #=> 13
puts 13.9.to_i #=> 13

# Even 
puts 6.even? #=> true
puts 7.even? #=> false

# Odd
puts 6.odd? #=> false
puts 7.odd? #=> true

